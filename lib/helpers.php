<?php

declare(strict_types=1);

/**
 * Глобальные функции-помощники DBitter (без namespace, чтобы вызывать их
 * коротко из любого места). Подключаются из lib/bootstrap.php. Дают доступ
 * к корню инструмента (константа DbTools\ROOT), имени проекта и генератору
 * уникальных меток времени для имён дампов и манифестов (см. Dump::baseName).
 */

/**
 * Возвращает абсолютный путь к корню инструмента (каталог DBitter).
 * Используется для построения путей к config.php, conf/, dump/ и т.п.
 *
 * @return string Путь без завершающего слэша.
 */
function dbt_root(): string
{
    return \DbTools\ROOT;
}

/**
 * Возвращает имя проекта — basename родительского каталога инструмента
 * (например, "3406" для D:/_sites/3406/DBitter). Идёт в имена дампов
 * и манифесты как идентификатор проекта. Если инструмент лежит внутри
 * проекта, это имя каталога проекта; если вынесен наружу — имя его
 * родительского каталога (для пакетного режима будет переопределяться).
 *
 * @return string Имя каталога проекта.
 */
function dbt_project(): string
{
    return basename(dirname(\DbTools\ROOT));
}

/**
 * Метка времени для имён файлов дампов/манифестов: "Ymd-His-xxx".
 *
 * @return string Например, "20261110-153045-a1b".
 */
function dbt_now(): string
{
    // Одной точности до секунды недостаточно: два экспорта в пределах одной
    // секунды перезаписали бы файлы друг друга. Короткий случайный суффикс
    // (3 hex-символа из 2 случайных байт) гарантирует уникальность имён.
    return date('Ymd-His') . '-' . substr(bin2hex(random_bytes(2)), 0, 3);
}
